import uuid
from datetime import datetime
from enum import StrEnum

from pgvector.sqlalchemy import Vector
from sqlalchemy import (
    BigInteger,
    CheckConstraint,
    Computed,
    DateTime,
    ForeignKeyConstraint,
    Index,
    Integer,
    String,
    Text,
    UniqueConstraint,
    text,
)
from sqlalchemy.dialects.postgresql import TSVECTOR, UUID
from sqlalchemy.orm import Mapped, mapped_column

from sqa.models.base import Base, OrgScoped, TimestampMixin

# Fixed so the HNSW index has a dimension. Every embedding provider is asked
# for vectors of this size (Voyage `output_dimension`, OpenAI `dimensions`).
EMBEDDING_DIM = 1024

SEARCH_TSV_EXPR = "to_tsvector('english', coalesce(heading, '') || ' ' || text)"


class DocumentKind(StrEnum):
    PDF = "pdf"
    DOCX = "docx"
    XLSX = "xlsx"


class DocumentStatus(StrEnum):
    QUEUED = "queued"
    PROCESSING = "processing"
    READY = "ready"
    FAILED = "failed"


class Document(Base, OrgScoped, TimestampMixin):
    __tablename__ = "documents"
    __table_args__ = (
        # Target of the composite FK from chunks: a chunk's org must match its document's.
        UniqueConstraint("org_id", "id", name="uq_documents_org_id_id"),
        # Same bytes uploaded twice in one org -> one document.
        UniqueConstraint("org_id", "sha256", name="uq_documents_org_sha256"),
        CheckConstraint("kind IN ('pdf', 'docx', 'xlsx')", name="kind_valid"),
        CheckConstraint(
            "status IN ('queued', 'processing', 'ready', 'failed')", name="status_valid"
        ),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )
    filename: Mapped[str] = mapped_column(String(255), nullable=False)
    kind: Mapped[str] = mapped_column(String(8), nullable=False)
    content_type: Mapped[str] = mapped_column(String(128), nullable=False)
    size_bytes: Mapped[int] = mapped_column(BigInteger, nullable=False)
    sha256: Mapped[str] = mapped_column(String(64), nullable=False)
    storage_key: Mapped[str] = mapped_column(String(512), nullable=False)
    # PDF rendition of a DOCX, so citations can point at real pages.
    rendition_key: Mapped[str | None] = mapped_column(String(512))
    status: Mapped[str] = mapped_column(
        String(16), nullable=False, server_default=DocumentStatus.QUEUED.value
    )
    # Machine-readable reason only; never an exception message.
    error_code: Mapped[str | None] = mapped_column(String(32))
    # Which extractor produced the chunks, e.g. "pymupdf", "libreoffice+pymupdf".
    parser: Mapped[str | None] = mapped_column(String(32))
    page_count: Mapped[int | None] = mapped_column(Integer)
    chunk_count: Mapped[int] = mapped_column(Integer, nullable=False, server_default="0")
    uploaded_by: Mapped[str | None] = mapped_column(String(64))
    processed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))

    @property
    def has_rendition(self) -> bool:
        return self.rendition_key is not None


class DocumentChunk(Base, OrgScoped, TimestampMixin):
    """A retrievable passage, with enough location data to cite it."""

    __tablename__ = "document_chunks"
    __table_args__ = (
        ForeignKeyConstraint(
            ["org_id", "document_id"],
            ["documents.org_id", "documents.id"],
            ondelete="CASCADE",
            name="fk_chunks_document_same_org",
        ),
        UniqueConstraint("document_id", "ordinal"),
        Index("ix_document_chunks_org_document", "org_id", "document_id"),
    )

    id: Mapped[uuid.UUID] = mapped_column(
        UUID(as_uuid=True), primary_key=True, server_default=text("gen_random_uuid()")
    )
    document_id: Mapped[uuid.UUID] = mapped_column(UUID(as_uuid=True), nullable=False)
    ordinal: Mapped[int] = mapped_column(Integer, nullable=False)
    text: Mapped[str] = mapped_column(Text, nullable=False)
    # Section path joined with " > ", e.g. "Security > Access Control".
    heading: Mapped[str | None] = mapped_column(Text)
    page_start: Mapped[int | None] = mapped_column(Integer)
    page_end: Mapped[int | None] = mapped_column(Integer)
    sheet: Mapped[str | None] = mapped_column(String(200))
    row_start: Mapped[int | None] = mapped_column(Integer)
    row_end: Mapped[int | None] = mapped_column(Integer)
    embedding: Mapped[list[float]] = mapped_column(Vector(EMBEDDING_DIM), nullable=False)
    embedding_model: Mapped[str] = mapped_column(String(100), nullable=False)
    # Generated by Postgres, for keyword search alongside vectors (Phase 1c).
    search_tsv: Mapped[str] = mapped_column(
        TSVECTOR, Computed(SEARCH_TSV_EXPR, persisted=True), deferred=True
    )
